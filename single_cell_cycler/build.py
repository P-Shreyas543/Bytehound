"""Build script for Bytehound Single-Cell BMS Cycler executable using PyInstaller.

Usage:
    python single_cell_cycler/build.py              # Clean + Build (onedir) + Zip
    python single_cell_cycler/build.py --onefile    # Build single standalone .exe
    python single_cell_cycler/build.py --console    # Build with debug console window
    python single_cell_cycler/build.py --no-clean   # Incremental build without wiping dist/
    python single_cell_cycler/build.py --no-zip     # Skip creating the distribution .zip

Output:
    dist/SingleCellCycler/SingleCellCycler.exe       (onedir bundle)
    dist/SingleCellCycler_v1.0.0_win64.zip          (distributable release archive)
"""

from __future__ import annotations

import argparse
import json
import os
import shutil
import subprocess
import sys
import time
from pathlib import Path
import zipfile

# Resolve repository paths
SCRIPT_DIR = Path(__file__).resolve().parent
REPO_ROOT = SCRIPT_DIR.parent
APP_NAME = "SingleCellCycler"
MAIN_ENTRY = SCRIPT_DIR / "main.py"
SPEC_FILE = SCRIPT_DIR / "SingleCellCycler.spec"
DIST_DIR = REPO_ROOT / "dist"
BUILD_DIR = REPO_ROOT / "build" / APP_NAME
OUTPUT_DIR = DIST_DIR / APP_NAME
BRANDING_DIR = REPO_ROOT / "branding"
ICON_PATH = BRANDING_DIR / "logo.ico"


def get_app_version() -> str:
    """Read version from version.json in repo root or fallback to 1.0.0."""
    ver_file = REPO_ROOT / "version.json"
    if ver_file.exists():
        try:
            with open(ver_file, "r", encoding="utf-8") as f:
                data = json.load(f)
                return str(data.get("version", "1.0.0"))
        except Exception:
            pass
    return "1.0.0"


def clean_artifacts() -> None:
    """Clean previous build and dist directories."""
    print(f"[build] Cleaning previous build artifacts...")
    for target in (OUTPUT_DIR, BUILD_DIR):
        if target.exists():
            print(f"  Removing {target}")
            try:
                shutil.rmtree(target, ignore_errors=True)
            except Exception as e:
                print(f"  [warn] Could not remove {target}: {e}")


