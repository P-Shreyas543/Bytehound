def run_build(spec_path: Path) -> int:
    """Execute PyInstaller build."""
    cmd = [
        sys.executable,
        "-m",
        "PyInstaller",
        "--noconfirm",
        f"--distpath={DIST_DIR}",
        f"--workpath={REPO_ROOT / 'build'}",
        str(spec_path),
    ]
    print(f"[build] Executing: {' '.join(cmd)}")
    t0 = time.time()
    res = subprocess.call(cmd, cwd=REPO_ROOT)
    t1 = time.time()
    if res == 0:
        print(f"[build] PyInstaller compilation completed in {t1 - t0:.1f}s")
    else:
        print(f"[build] [ERROR] PyInstaller compilation failed with code {res}")
    return res


def create_distribution_zip(version: str, onefile: bool) -> Path:
    """Zip the output bundle for distribution."""
    zip_name = f"{APP_NAME}_v{version}_win64.zip"
    zip_path = DIST_DIR / zip_name
    print(f"[build] Creating release archive: {zip_path.name}...")

    if onefile:
        exe_file = DIST_DIR / f"{APP_NAME}.exe"
        if not exe_file.exists():
            raise FileNotFoundError(f"Expected binary {exe_file} not found")
        with zipfile.ZipFile(zip_path, "w", zipfile.ZIP_DEFLATED) as zf:
            zf.write(exe_file, arcname=exe_file.name)
            # Add recipe templates
            recipes_dir = SCRIPT_DIR / "config" / "recipes"
            if recipes_dir.exists():
                for r in recipes_dir.glob("*.json"):
                    zf.write(r, arcname=f"recipes/{r.name}")
    else:
        if not OUTPUT_DIR.exists():
            raise FileNotFoundError(f"Expected directory {OUTPUT_DIR} not found")
        with zipfile.ZipFile(zip_path, "w", zipfile.ZIP_DEFLATED) as zf:
            for root, _, files in os.walk(OUTPUT_DIR):
                for file in files:
                    file_path = Path(root) / file
                    rel_path = file_path.relative_to(DIST_DIR)
                    zf.write(file_path, arcname=str(rel_path))

    size_mb = zip_path.stat().st_size / (1024 * 1024)
    print(f"[build] Release archive created successfully: {zip_path} ({size_mb:.1f} MB)")
    return zip_path


def main() -> int:
    parser = argparse.ArgumentParser(description="Build Single-Cell BMS Cycler executable.")
    parser.add_argument("--onefile", action="store_true", help="Build as a single standalone .exe")
    parser.add_argument("--console", action="store_true", help="Keep console window open (debug mode)")
    parser.add_argument("--no-clean", action="store_true", help="Do not wipe dist/ and build/ before building")
    parser.add_argument("--no-zip", action="store_true", help="Skip creating release zip archive")
    parser.add_argument("--spec-only", action="store_true", help="Generate the .spec file without building")
    args = parser.parse_args()

    version = get_app_version()
    print("=" * 65)
    print(f"   BYTEHOUND SINGLE-CELL BMS CYCLER BUILD TOOL (v{version})")
    print("=" * 65)
    print(f"Target Binary : {APP_NAME}.exe ({'Onefile' if args.onefile else 'Onedir'})")
    print(f"Console Mode  : {'Enabled (Debug)' if args.console else 'Disabled (Windowed)'}")
    print(f"Repository    : {REPO_ROOT}")

    if not args.no_clean and not args.spec_only:
        clean_artifacts()

    # Ensure output dist directory exists
    DIST_DIR.mkdir(parents=True, exist_ok=True)

    spec_path = generate_spec_file(onefile=args.onefile, console=args.console)
    if args.spec_only:
        print("[build] Spec file generated. Exiting due to --spec-only flag.")
        return 0

    build_code = run_build(spec_path)
    if build_code != 0:
        return build_code

    # Verify build results
    target_exe = (DIST_DIR / f"{APP_NAME}.exe") if args.onefile else (OUTPUT_DIR / f"{APP_NAME}.exe")
    if not target_exe.exists():
        print(f"[build] [ERROR] Expected executable {target_exe} was not produced!")
        return 1

    print("\n" + "=" * 65)
    print(f"   BUILD SUCCEEDED: {target_exe.name}")
    print(f"   Executable Location: {target_exe}")
    print("=" * 65)

    if not args.no_zip:
        create_distribution_zip(version, onefile=args.onefile)

    print("\n[build] All build steps completed successfully!")
    print(f"Run the application with: {target_exe}\n")
    return 0


if __name__ == "__main__":
    sys.exit(main())
